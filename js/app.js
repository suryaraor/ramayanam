function enterFullscreen() {
  const el = document.documentElement;
  if (document.fullscreenElement || document.webkitFullscreenElement) return;
  try {
    const p = (el.requestFullscreen?.({ navigationUI: 'hide' }) ?? el.webkitRequestFullscreen?.());
    p?.catch?.(() => {});
  } catch { /* not allowed */ }
}
function exitFullscreen() {
  if (document.fullscreenElement) document.exitFullscreen().catch(() => {});
  else if (document.webkitFullscreenElement) document.webkitExitFullscreen?.();
}

function openFromClick(m) {
  enterFullscreen();             // must run inside the click gesture
  V.fsAsked = true;
  history.pushState({ viewer: true }, '', `#read=${encodeURIComponent(m.file)}`);
  V.pushed = true;
  route();
}

function goHome() {
  if (!V.m) return;
  if (V.pushed && history.state?.viewer) history.back();
  else { history.replaceState(null, '', location.pathname + location.search); route(); }
}

function parseHash() {
  const p = new URLSearchParams(location.hash.slice(1));
  const file = p.get('read');
  return file ? { file, page: parseInt(p.get('p'), 10) || 1 } : null;
}

async function route() {
  const want = parseHash();
  if (!want) { closeViewer(); return; }
  if (V.m && V.m.file === want.file) return;
  let m = catalog.find((x) => x.file === want.file);
  if (!m) {
    const name = want.file.split('/').pop();
    if (!/\.pdf$/i.test(name) || want.file.includes('..')) { closeViewer(); return; }
    m = { file: want.file, name, title: titleFromName(name) };
  }
  openViewer(m, want.page);
}

async function openViewer(m, startPage = 1) {
  const gen = ++V.gen;
  V.m = m;
  V.page = 1;
  V.count = 0;
  V.cache.clear();
  V.busy = false;
  V.queued = 0;
  document.body.classList.add('reading');
  document.title = `${m.title} · శ్రీమద్రామాయణము`;
  viewer.hidden = false;
  viewer.classList.remove('enter');
  void viewer.offsetWidth;
  viewer.classList.add('enter');
  viewer.classList.toggle('muted', !soundOn);
  viewer.classList.toggle('fitw', V.fitW);
  scroller.scrollTop = 0;
  $('#vTitle').textContent = m.title;
  $('#vPage').textContent = '';
  $('#progressBar').style.width = '0';
  leafBase.replaceChildren();
  resetZoom();
  book.style.width = book.style.height = '0';
  spinner.hidden = false;
  showHud(true);

  if (!store.get('mag.coach')) $('#coach').hidden = false;

  let lib;
  try { lib = await pdfjs(); } catch (err) {
    // This browser can't run PDF.js: open the PDF in the browser's own viewer instead
    console.error(err);
    location.href = fileUrl(m);
    return;
  }
  try {
    const doc = await lib.getDocument({ url: fileUrl(m), ...PDF_OPTS }).promise;
    if (gen !== V.gen) { doc.destroy(); return; }
    V.doc = doc;
    V.count = doc.numPages;
    m.pages = doc.numPages;
    const first = await doc.getPage(1);
    V.size = first.getViewport({ scale: 1 });
    layoutBook();
    V.page = Math.min(Math.max(1, startPage), V.count);
    await showPage(V.page);
    prefetch();
    saveOffline(m, doc);
  } catch (err) {
    if (gen !== V.gen) return;
    console.error(err);
    spinner.hidden = true;
    toast(navigator.onLine ? 'క్షమించండి, ఈ భాగం తెరవలేకపోయాం.'
      : 'ఇంటర్నెట్ లేదు. ఆఫ్‌లైన్‌లో చదవాలంటే ఒకసారి ఇంటర్నెట్ ఉన్నప్పుడు తెరవండి.', 4500);
  }
}

function closeViewer() {
  if (!V.m) return;
  V.gen++;
  V.m = null;
  V.doc?.destroy();
  V.doc = null;
  for (const p of V.cache.values()) p.then((c) => { c.width = c.height = 0; }).catch(() => {});
  V.cache.clear();
  leafBase.replaceChildren();
  flipFront.replaceChildren();
  leafFlip.classList.remove('on');
  resetZoom();
  pts.clear();
  pinch = ptr = null;
  stage.style.transform = stage.style.opacity = '';
  viewer.hidden = true;
  $('#coach').hidden = true;
  document.body.classList.remove('reading');
  document.title = 'శ్రీమద్రామాయణము · Srimad Ramayanam';
  V.fsAsked = false;
  V.pushed = false;
  exitFullscreen();
}

function fit(vp) {
  if (V.fitW) {
    // Full width of the reader, minus its scrollbar; height runs as long as it needs.
    const s = (scroller.clientWidth || window.innerWidth) / vp.width;
    return { w: Math.floor(vp.width * s), h: Math.floor(vp.height * s), s };
  }
  const W = window.innerWidth;
  const H = window.innerHeight;
  const pad = W < 700 ? 0 : 24;
  const s = Math.min((W - pad * 2) / vp.width, (H - pad * 2) / vp.height);
  return { w: Math.floor(vp.width * s), h: Math.floor(vp.height * s), s };
}

function layoutBook() {
  if (!V.size) return;
  const { w, h } = fit(V.size);
  book.style.width = `${w}px`;
  book.style.height = `${h}px`;
}

function getPageCanvas(n) {
  let p = V.cache.get(n);
  if (p) return p;
  const doc = V.doc;
  p = (async () => {
    const page = await doc.getPage(n);
    const vp1 = page.getViewport({ scale: 1 });
    let scale = fit(vp1).s * Math.min(devicePixelRatio || 1, 2.5);
    const maxPx = 12e6;
    if (vp1.width * vp1.height * scale * scale > maxPx) scale = Math.sqrt(maxPx / (vp1.width * vp1.height));
    const vp = page.getViewport({ scale });
    const c = document.createElement('canvas');
    c.width = Math.floor(vp.width);
    c.height = Math.floor(vp.height);
    await page.render({ canvasContext: c.getContext('2d'), viewport: vp }).promise;
    return c;
  })();
  V.cache.set(n, p);
  p.catch(() => V.cache.delete(n));
  return p;
}

function prefetch() {
  if (!V.doc) return;
  const gen = V.gen;
  const order = [V.page + 1, V.page - 1, V.page + 2];
  (async () => {
    for (const n of order) {
      if (gen !== V.gen || n < 1 || n > V.count) continue;
      await getPageCanvas(n).catch(() => {});
    }
  })();
  for (const [n, p] of V.cache) {
    if (Math.abs(n - V.page) > 3) {
      V.cache.delete(n);
      p.then((c) => { c.width = c.height = 0; }).catch(() => {});
    }
  }
}

async function showPage(n) {
  const gen = V.gen;
  spinner.hidden = false;
  const c = await getPageCanvas(n);
  if (gen !== V.gen) return;
  const shade = document.createElement('div');
  shade.className = 'lift-shade';
  leafBase.replaceChildren(c, shade);
  spinner.hidden = true;
  updateHud();
}

function updateHud() {
  $('#vPage').textContent = V.count ? `Page ${V.page} of ${V.count}` : '';
  $('#progressBar').style.width = V.count ? `${(V.page / V.count) * 100}%` : '0';
  if (V.m) history.replaceState(history.state, '', `#read=${encodeURIComponent(V.m.file)}${V.page > 1 ? `&p=${V.page}` : ''}`);
}

const reduceMotion = matchMedia('(prefers-reduced-motion: reduce)').matches;

async function flip(dir, { toEnd = false } = {}) {
  if (!V.doc) return;
  if (zoomed() || pinch) { pinch = null; resetZoom(); }
  if (V.busy) { V.queued = Math.max(-5, Math.min(5, V.queued + dir)); return; }
  const target = V.page + dir;
  if (target < 1 || target > V.count) {
    V.queued = 0;
    book.classList.remove('bump');
    void book.offsetWidth;
    book.classList.add('bump');
    toast(target < 1 ? 'ఇది మొదటి పేజీ' : 'ఈ భాగం పూర్తయింది. అన్ని భాగాలకు కుడి నుంచి ఎడమకు స్వైప్ చేయండి.');
    return;
  }
  V.busy = true;
  const gen = V.gen;
  try {
    if (!V.cache.has(target)) spinner.hidden = false;
    const [cur, nxt] = await Promise.all([getPageCanvas(V.page), getPageCanvas(target)]);
    if (gen !== V.gen) return;
    spinner.hidden = true;
    playFlip();

    if (V.fitW) {
      // Fit to width reads like a scroll: the next page slides up from below,
      // the previous one comes down from above, scrolled to its end.
      const shade = document.createElement('div');
      shade.className = 'lift-shade';
      leafBase.replaceChildren(nxt, shade);
      V.page = target;
      scroller.scrollTop = dir < 0 && toEnd ? scroller.scrollHeight : 0;
      wheel.lockUntil = performance.now() + 500;
      updateHud();
      prefetch();
      if (!reduceMotion) {
        await book.animate([{ transform: `translateY(${dir * 48}px)`, opacity: 0 }, { transform: 'none', opacity: 1 }],
          { duration: 260, easing: 'ease-out' }).finished;
      }
      return;
    }

    const curl = document.createElement('div');
    curl.className = 'curl-shade';
    const baseShade = document.createElement('div');
    baseShade.className = 'lift-shade';
    const dur = reduceMotion ? 220 : 700;
    const ease = 'cubic-bezier(.45,.05,.35,1)';

    let turning, under;
    if (dir > 0) { turning = cur; under = nxt; } else { turning = nxt; under = cur; }
    leafBase.replaceChildren(under, baseShade);
    flipFront.replaceChildren(turning, curl);
    leafFlip.classList.add('on');

    // Keyframes for turning forward; going back plays the same motion in reverse.
    const turnK = [
      { transform: 'rotateY(0deg)' },
      { transform: 'rotateY(-90deg) skewY(-2deg)', offset: 0.5 },
      { transform: 'rotateY(-180deg)' },
    ];
    const curlK = [{ opacity: 0 }, { opacity: 0.9, offset: 0.45 }, { opacity: 0 }];
    const backK = [{ opacity: 1 }, { opacity: 1, offset: 0.7 }, { opacity: 0 }];   // paper back fades as it lands off-page
    const baseK = [{ opacity: 1 }, { opacity: 0.6, offset: 0.4 }, { opacity: 0 }]; // shadow on the page underneath
    const opts = { duration: dur, easing: ease, fill: 'both', direction: dir > 0 ? 'normal' : 'reverse' };
    const back = leafFlip.querySelector('.face.back');

    const anims = [
      leafFlip.animate(turnK, opts),
      curl.animate(curlK, opts),
      back.animate(backK, opts),
      baseShade.animate(baseK, opts),
    ];
    await Promise.all(anims.map((a) => a.finished));
    if (gen !== V.gen) return;

    V.page = target;
    const shade = document.createElement('div');
    shade.className = 'lift-shade';
    leafBase.replaceChildren(nxt, shade);
    flipFront.replaceChildren();
    leafFlip.classList.remove('on');
    anims.forEach((a) => a.cancel());
    updateHud();
    prefetch();
  } catch (err) {
    console.error(err);
    spinner.hidden = true;
  } finally {
    V.busy = false;
    if (V.queued && gen === V.gen) {
      const step = Math.sign(V.queued);
      V.queued -= step;
      flip(step, { toEnd });
    }
  }
}

