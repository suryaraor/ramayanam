/* Lazy cover thumbnails, two at a time. Only page 1 is fetched (range requests). */
const coverQueue = [];
let coverActive = 0;
const coverObserver = new IntersectionObserver((entries) => {
  for (const en of entries) {
    if (!en.isIntersecting) continue;
    coverObserver.unobserve(en.target);
    coverQueue.push(catalog[+en.target.dataset.i]);
  }
  pumpCovers();
}, { rootMargin: '300px' });

function pumpCovers() {
  while (coverActive < 2 && coverQueue.length) {
    const m = coverQueue.shift();
    coverActive++;
    renderCover(m).catch(() => {}).finally(() => { coverActive--; pumpCovers(); });
  }
}

async function renderCover(m) {
  if (m.cover) return;   // a ready-made cover image is already showing
  const canvas = $('.cover canvas', m._el);
  const doc = await (await pdfjs()).getDocument({ url: fileUrl(m), disableAutoFetch: true, disableStream: true, ...PDF_OPTS }).promise;
  try {
    m.pages = doc.numPages;
    $('.sub', m._el).textContent = subline(m);
    const page = await doc.getPage(1);
    const vp1 = page.getViewport({ scale: 1 });
    const targetW = Math.min(canvas.parentElement.clientWidth * Math.min(devicePixelRatio || 1, 2), 900);
    const vp = page.getViewport({ scale: targetW / vp1.width });
    canvas.width = Math.floor(vp.width);
    canvas.height = Math.floor(vp.height);
    await page.render({ canvasContext: canvas.getContext('2d'), viewport: vp }).promise;
    canvas.classList.add('ready');
    $('.cover-ph', m._el)?.remove();
  } finally {
    doc.destroy();
  }
}

/* ------------------------------------------------------------------ *
 * Paper-flip sound (synthesised, no audio file needed)
 * ------------------------------------------------------------------ */
let soundOn = store.get('mag.sound') !== 'off';
let actx, flipBuf;

function makeFlipBuffer(ctx) {
  const sr = ctx.sampleRate;
  const dur = 0.55;
  const n = Math.floor(sr * dur);
  const buf = ctx.createBuffer(1, n, sr);
  const d = buf.getChannelData(0);
  let brown = 0;
  for (let i = 0; i < n; i++) {
    const t = i / sr;
    // swell while the page lifts, then a quick "slap" as it lands
    const swell = Math.pow(Math.sin(Math.PI * Math.min(t / 0.42, 1)), 1.6) * (t < 0.42 ? 1 : 0);
    const slap = t > 0.36 ? Math.exp(-(t - 0.36) * 38) * 1.4 : 0;
    const white = Math.random() * 2 - 1;
    brown = (brown + 0.02 * white) / 1.02;
    const crackle = Math.random() < 0.015 ? white * 2.2 : 0;
    d[i] = (white * 0.55 + brown * 3 + crackle) * (swell * 0.7 + slap);
  }
  return buf;
}

function playFlip() {
  if (!soundOn) return;
  try {
    actx ||= new (window.AudioContext || window.webkitAudioContext)();
    if (actx.state === 'suspended') actx.resume();
    flipBuf ||= makeFlipBuffer(actx);
    const t0 = actx.currentTime;
    const src = actx.createBufferSource();
    src.buffer = flipBuf;
    src.playbackRate.value = 0.92 + Math.random() * 0.16;
    const bp = actx.createBiquadFilter();
    bp.type = 'bandpass';
    bp.Q.value = 0.7;
    bp.frequency.setValueAtTime(900, t0);
    bp.frequency.exponentialRampToValueAtTime(3800, t0 + 0.25);
    bp.frequency.exponentialRampToValueAtTime(1400, t0 + 0.5);
    const hp = actx.createBiquadFilter();
    hp.type = 'highpass';
    hp.frequency.value = 250;
    const g = actx.createGain();
    g.gain.value = 0.9;
    src.connect(bp).connect(hp).connect(g).connect(actx.destination);
    src.start();
  } catch { /* audio unavailable */ }
}

